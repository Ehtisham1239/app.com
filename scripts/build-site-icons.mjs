// Preserve the pinned Lucide artwork while moving repeated SVG paths out of HTML
// and the React Server Component payload. Admin icons keep their existing API.
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from "node:fs";
import { createHash } from "node:crypto";
import * as lucide from "lucide-react";

const walk = dir => readdirSync(dir, { withFileTypes: true }).flatMap(entry => entry.isDirectory() ? walk(`${dir}/${entry.name}`) : [`${dir}/${entry.name}`]);
const files = [...walk("src/app/(site)"), ...walk("src/components/site"), "src/components/icon.jsx"].filter(path => path.endsWith(".jsx"));
const names = new Set();
for (const path of files) {
  for (const match of readFileSync(path, "utf8").matchAll(/import\s*\{([^}]+)\}\s*from\s*["'](?:lucide-react|@\/components\/site\/icons)["']/g)) {
    for (const name of match[1].split(",").map(value => value.trim()).filter(Boolean)) names.add(name);
  }
}
const escape = value => String(value).replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;");
const symbols = new Map(), entries = [];
for (const name of [...names].sort()) {
  const icon = lucide[name]?.render({}, null).props.icon;
  if (!icon) throw Error(`Unknown pinned Lucide icon: ${name}`);
  symbols.set(icon.name, `<symbol id="${icon.name}" viewBox="0 0 24 24">${icon.node.map(([tag, attributes]) => `<${tag} ${Object.entries(attributes).filter(([key]) => key !== "key").map(([key, value]) => `${key}="${escape(value)}"`).join(" ")}/>`).join("")}</symbol>`);
  entries.push(`export const ${name} = props => <SiteIcon name="${icon.name}" {...props} />;`);
}
const license = readFileSync("node_modules/lucide-react/LICENSE", "utf8");
const svg = `<svg xmlns="http://www.w3.org/2000/svg"><metadata>${escape(license)}</metadata>${[...symbols.values()].join("")}</svg>\n`;
const asset = `site-icons-${createHash("sha256").update(svg).digest("hex").slice(0, 12)}.svg`;
mkdirSync("public/icons", { recursive: true });
writeFileSync(`public/icons/${asset}`, svg);
const mappings = Object.fromEntries([...readFileSync("src/components/icon.jsx", "utf8").split("export const CONTENT_ICONS = {")[1].split("};")[0].matchAll(/(?:"([a-z-]+)"|([a-z]+)):\s*(\w+)/g)].map(([, quoted, bare, component]) => [quoted || bare, lucide[component].render({}, null).props.icon.name]));
writeFileSync("src/lib/site-icon-names.js", `// Generated from the existing CMS icon names and pinned Lucide artwork.\nexport const CONTENT_ICON_SYMBOLS = ${JSON.stringify(mappings, null, 2)};\n`);
writeFileSync("src/components/site/icons.jsx", `// Generated by scripts/build-site-icons.mjs from the pinned Lucide dependency.\nexport function SiteIcon({ name, className = "", strokeWidth = 2, ...props }) {\n  return <svg viewBox="0 0 24 24" width="24" height="24" className={\`site-icon \${className}\`} strokeWidth={strokeWidth} aria-hidden="true" focusable="false" {...props}><use href={\`/icons/${asset}#\${name}\`} /></svg>;\n}\n${entries.join("\n")}\n`);
console.log(`Generated ${symbols.size} shared glyphs in ${asset} (${Buffer.byteLength(svg)} bytes).`);
