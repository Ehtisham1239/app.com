import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const base=process.env.SMOKE_BASE_URL || 'http://localhost:3000';
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH || '/usr/bin/chromium',headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto(`${base}/`,{waitUntil:'networkidle'});
await page.getByRole('link',{name:'CMS Portal',exact:true}).first().click();
await page.waitForURL('**/admin/login');
await page.getByLabel('Email',{exact:true}).waitFor();
await page.getByRole('button',{name:'Sign in',exact:true}).waitFor();
console.log('PASS CMS button → protected login');
await page.goto(`${base}/locations/united-kingdom/london?utm_source=google&utm_medium=cpc&utm_campaign=london-quran`,{waitUntil:'networkidle'});
await page.getByRole('heading',{level:1,name:'Online Quran classes in London, United Kingdom'}).waitFor();
await page.screenshot({path:'/tmp/oqc-desktop.png',fullPage:true});
await page.getByRole('link',{name:'Book a free trial in London',exact:true}).click();
await page.waitForURL('**/free-trial?**');
const attribution=await page.evaluate(()=>JSON.parse(sessionStorage.getItem('oqc-campaign')));
assert.equal(attribution.data.utm_campaign,'london-quran');
await page.getByRole('button',{name:/Continue/}).first().waitFor();
console.log('PASS campaign landing → trial form retains attribution');
await page.goto(`${base}/pricing`,{waitUntil:'networkidle'});
await page.getByLabel('Display currency',{exact:true}).first().selectOption('GBP');
await page.getByText('Ask for the fee in GBP').first().waitFor();
await page.getByLabel('Display currency',{exact:true}).first().selectOption('NOK');
await page.getByText('Ask for the fee in NOK').first().waitFor();
console.log('PASS unpriced GBP and NOK show quote requests');
for(const [country,city,currency] of [['united-states','new-york','USD'],['united-kingdom','london','GBP'],['australia','sydney','AUD'],['canada','toronto','CAD'],['france','paris','EUR'],['germany','berlin','EUR']]){
 const response=await page.goto(`${base}/locations/${country}/${city}`,{waitUntil:'networkidle'});
 assert.equal(response.status(),200);
 assert.ok((await page.locator('body').innerText()).includes(currency));
}
console.log('PASS requested 6 country/city markets');
await page.setViewportSize({width:390,height:844});
await page.goto(`${base}/`,{waitUntil:'networkidle'});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
await page.getByRole('button',{name:'Open menu',exact:true}).click();
await page.getByRole('navigation',{name:'Mobile'}).getByRole('link',{name:'Areas',exact:true}).click();
await page.waitForURL('**/locations');
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
await page.screenshot({path:'/tmp/oqc-mobile.png',fullPage:true});
console.log('PASS mobile menu, Areas navigation and no horizontal overflow');
const bad=await page.goto(`${base}/locations/united-kingdom/not-a-city`);assert.equal(bad.status(),404);
assert.deepEqual(errors,[]);console.log('PASS invalid city 404; no browser JavaScript errors');
await browser.close();
